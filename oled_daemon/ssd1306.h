/* ── Framebuffer ────────────────────────────────────────────────────────── *
 * Layout: framebuf[page * 128 + col]
 *   page 0-7 top-to-bottom, col 0-127 left-to-right
 *   within each byte: bit 0 = top of page, bit 7 = bottom
 */
static uint8_t framebuf[SSD1306_FBSIZE];

static void fb_clear(void) { memset(framebuf, 0, SSD1306_FBSIZE); }

static void fb_putchar(int col, int page, char c)
{
    if (c < 32 || c > 127) c = '?';
    const uint8_t *g = font5x8[(uint8_t)c - 32];
    int base = page * SSD1306_W + col;
    for (int i = 0; i < 5 && col + i < SSD1306_W; i++)
        framebuf[base + i] = g[i];
    if (col + 5 < SSD1306_W)
        framebuf[base + 5] = 0x00;
}

/* Write up to FONT_COLS characters starting at (col_char, page). */
static void fb_puts(int col_char, int page, const char *s)
{
    int col = col_char * FONT_W;
    while (*s && col + FONT_W <= SSD1306_W) {
        fb_putchar(col, page, *s++);
        col += FONT_W;
    }
}

/* Clear one text row (all 128 pixels on a page). */
static void fb_clearrow(int page)
{
    memset(framebuf + page * SSD1306_W, 0, SSD1306_W);
}

/* ── SSD1306 I2C driver ─────────────────────────────────────────────────── */

static int ssd1306_open(const char *dev, uint8_t addr)
{
    int fd = open(dev, O_RDWR);
    if (fd < 0) return -1;
    if (ioctl(fd, I2C_SLAVE, addr) < 0) { close(fd); return -1; }
    return fd;
}

static void ssd1306_cmd(int fd, uint8_t c)
{
    uint8_t buf[2] = {0x00, c};
    write(fd, buf, 2);
}

static void ssd1306_cmd2(int fd, uint8_t c0, uint8_t c1)
{
    uint8_t buf[3] = {0x00, c0, c1};
    write(fd, buf, 3);
}

static void ssd1306_init(int fd)
{
    ssd1306_cmd (fd, 0xAE);        /* display off          */
    ssd1306_cmd2(fd, 0xD5, 0x80);  /* clock divider        */
    ssd1306_cmd2(fd, 0xA8, 0x3F);  /* mux ratio 64         */
    ssd1306_cmd2(fd, 0xD3, 0x00);  /* display offset 0     */
    ssd1306_cmd (fd, 0x40);        /* start line 0         */
    ssd1306_cmd2(fd, 0x8D, 0x14);  /* charge pump on       */
    ssd1306_cmd2(fd, 0x20, 0x00);  /* horizontal addr mode */
    ssd1306_cmd (fd, 0xA1);        /* seg remap            */
    ssd1306_cmd (fd, 0xC8);        /* COM scan remapped    */
    ssd1306_cmd2(fd, 0xDA, 0x12);  /* COM pins             */
    ssd1306_cmd2(fd, 0x81, 0xCF);  /* contrast             */
    ssd1306_cmd2(fd, 0xD9, 0xF1);  /* precharge            */
    ssd1306_cmd2(fd, 0xDB, 0x40);  /* VCOMH                */
    ssd1306_cmd (fd, 0xA4);        /* output follows RAM   */
    ssd1306_cmd (fd, 0xA6);        /* normal (non-inverse) */
    ssd1306_cmd (fd, 0xAF);        /* display on           */
}

/* Flush the full 1024-byte framebuffer to the display in one write. */
static void ssd1306_flush(int fd)
{
    /* Set full display address window */
    uint8_t range[7] = {0x00,
                         0x21, 0x00, 0x7F,  /* column 0-127  */
                         0x22, 0x00, 0x07};  /* page   0-7    */
    write(fd, range, sizeof(range));

    /* Control byte 0x40 + 1024 data bytes in one syscall */
    static uint8_t txbuf[1 + SSD1306_FBSIZE];
    txbuf[0] = 0x40;
    memcpy(txbuf + 1, framebuf, SSD1306_FBSIZE);
    write(fd, txbuf, sizeof(txbuf));
}
